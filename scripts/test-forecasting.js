'use strict';
const assert=require('node:assert/strict');
const {probability,brier,earthquakeForecast,growthForecast,createForecasts}=require('../forecasting');
const DAY=86400000,end=Date.parse('2026-10-03T00:00:00Z'),start=end-3652*DAY,split=end-730*DAY;
assert.ok(probability(10,1000,90)>probability(10,1000,30));
assert.ok(probability(20,1000,30)>probability(10,1000,30));
assert.equal(brier([{probability:1,outcome:1},{probability:0,outcome:0}]),0);
assert.equal(brier([{probability:0,outcome:1}]),1);
const event=(time,mag=7)=>({properties:{time,mag}});
const training=Array.from({length:30},(_,i)=>event(start+(i+1)*50*DAY));
const a=earthquakeForecast(training,{threshold:7,horizon:30,start,end,url:'https://example.com'});
const b=earthquakeForecast([...training,event(split+DAY),event(end)],{threshold:7,horizon:30,start,end,url:'https://example.com'});
assert.equal(a.validation.trials[0].probability,b.validation.trials[0].probability,'Held-out events must not affect fitted backtest probabilities');
assert.equal(a.validation.trials[0].outcome,0);assert.equal(b.validation.trials[0].outcome,1);
assert.equal(b.baseline.events,31,'Window end is exclusive');
assert.equal(a.validation.windows,24);assert.ok(a.probability>=0&&a.probability<=1);
const years=Array.from({length:60},(_,i)=>({date:String(1966+i),value:i%5===0?-1:4}));
const growth=growthForecast(years,{positive:true,url:'https://example.com',now:end});
const modified=years.map((r,i)=>i>=45?{...r,value:-5}:r);
const changed=growthForecast(modified,{positive:true,url:'https://example.com',now:end});
assert.equal(growth.validation.trials[0].probability,changed.validation.trials[0].probability);
assert.notEqual(growth.probability,changed.probability);
assert.equal(growth.windowStart,'2026-01-01T00:00:00.000Z');
assert.throws(()=>growthForecast(years.filter(r=>Number(r.date)<2020),{positive:false,url:'https://example.com',now:end}),/too old/);
(async()=>{
  let calls=0;const get=createForecasts(async url=>{calls++;if(url.includes('usgs'))return {ok:true,json:async()=>({features:training})};throw Error('Economic source offline');},()=>end);
  const [first,second]=await Promise.all([get(),get()]);assert.equal(first,second);assert.equal(calls,2);
  assert.equal(first.forecasts.length,2);assert.equal(first.sources[1].status,'unavailable');assert.equal((await get()).cached,true);
  const missing=await createForecasts(async()=>{throw Error('Offline');},()=>end)();assert.equal(missing.forecasts.length,0);
  console.log('Forecast checks passed: chronological isolation, boundary rules, monotonic probabilities, Brier scoring, annual data lag, caching, and partial outages.');
})().catch(e=>{console.error(e);process.exitCode=1;});
